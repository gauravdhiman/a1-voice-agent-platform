"""Direct LinkedIn OpenID Connect OAuth broker.

LinkedIn does not expose a browser SDK that returns an ID token like Google
Identity Services. This module owns the confidential authorization-code exchange
and returns a verified LinkedIn profile for backend Supabase session creation.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any, Callable, Mapping
from urllib.parse import urlencode

import httpx

from shared.config import settings as default_settings

from .oauth_identity import OAuthVerifiedIdentity
from .oauth_state import create_signed_state, validate_signed_state

logger = logging.getLogger(__name__)

LINKEDIN_AUTHORIZATION_URL = "https://www.linkedin.com/oauth/v2/authorization"
LINKEDIN_TOKEN_URL = "https://www.linkedin.com/oauth/v2/accessToken"
LINKEDIN_USERINFO_URL = "https://api.linkedin.com/v2/userinfo"
LINKEDIN_OAUTH_PURPOSE = "linkedin-oauth"
HTTP_TIMEOUT_SECONDS = 10.0


@dataclass(frozen=True)
class LinkedInVerifiedIdentity:
    """Verified LinkedIn profile used to mint a Supabase session."""

    email: str
    first_name: str
    last_name: str
    linkedin_sub: str
    picture: str | None
    terms_accepted: bool = False


class LinkedInOAuthConfigurationError(RuntimeError):
    """Raised when the direct LinkedIn OAuth broker is not configured."""


class LinkedInOAuthError(ValueError):
    """Raised when LinkedIn rejects or cannot complete an OAuth exchange."""


class LinkedInOAuthService:
    """Create direct LinkedIn authorization URLs and exchange callback codes.

    The service keeps the LinkedIn client secret on the backend. The browser
    sees only the public LinkedIn authorization URL; the backend validates the
    returned authorization code and produces a verified LinkedIn profile that
    can be converted into a Supabase session.

    Args:
        settings_config: Settings object containing application and LinkedIn
            credentials. The global application settings are used by default.
        http_client_factory: Async HTTP client factory. It is injectable so
            token and userinfo requests can be tested deterministically.
    """

    def __init__(
        self,
        settings_config: Any = default_settings,
        http_client_factory: Callable[..., Any] = httpx.AsyncClient,
    ) -> None:
        self.settings = settings_config
        self.http_client_factory = http_client_factory

    @property
    def redirect_uri(self) -> str:
        """Return the registered backend callback URL for LinkedIn."""
        return f"{self.settings.api_base_url.rstrip('/')}/api/v1/auth/linkedin/callback"

    def create_authorization_url(
        self,
        invitation_token: str | None = None,
        terms_accepted: bool = False,
    ) -> tuple[str, str]:
        """Create a direct LinkedIn authorization URL and signed state value."""
        self._ensure_configuration()
        state = create_signed_state(
            purpose=LINKEDIN_OAUTH_PURPOSE,
            redirect_uri=self.redirect_uri,
            jwt_secret_key=self.settings.jwt_secret_key,
            invitation_token=invitation_token,
            terms_accepted=terms_accepted,
        )
        query = urlencode(
            {
                "response_type": "code",
                "client_id": self.settings.linkedin_client_id,
                "redirect_uri": self.redirect_uri,
                "scope": self.settings.linkedin_oauth_scopes,
                "state": state,
            }
        )
        return f"{LINKEDIN_AUTHORIZATION_URL}?{query}", state

    async def exchange_code(self, code: str, state: str) -> OAuthVerifiedIdentity:
        """Exchange a LinkedIn authorization code for a verified profile.

        The state is validated before any provider request. LinkedIn's
        authorization code is exchanged with the client secret and the verified
        profile is returned for backend Supabase session creation.

        Args:
            code: One-time authorization code returned by LinkedIn.
            state: Signed state returned by LinkedIn and generated by this
                service's ``create_authorization_url`` method.

        Returns:
            Verified LinkedIn identity suitable for Supabase session minting.

        Raises:
            LinkedInOAuthError: If LinkedIn rejects the exchange or the identity
                has no verified email address.
            LinkedInOAuthConfigurationError: If required backend credentials
                are missing.
            ValueError: If the signed OAuth state is invalid or expired.
        """
        self._ensure_configuration()
        state_payload = validate_signed_state(
            state,
            purpose=LINKEDIN_OAUTH_PURPOSE,
            redirect_uri=self.redirect_uri,
            jwt_secret_key=self.settings.jwt_secret_key,
        )
        if not code or len(code) > 2048:
            raise LinkedInOAuthError("Invalid LinkedIn authorization code.")

        async with self.http_client_factory(timeout=HTTP_TIMEOUT_SECONDS) as client:
            token_response = await client.post(
                LINKEDIN_TOKEN_URL,
                data={
                    "grant_type": "authorization_code",
                    "code": code,
                    "redirect_uri": self.redirect_uri,
                    "client_id": self.settings.linkedin_client_id,
                    "client_secret": self.settings.linkedin_client_secret,
                },
            )
            if token_response.status_code != 200:
                logger.warning(
                    "LinkedIn authorization-code exchange failed with status %s",
                    token_response.status_code,
                )
                raise LinkedInOAuthError(
                    "LinkedIn authorization could not be completed."
                )

            token_data = token_response.json()
            linkedin_access_token = token_data.get("access_token")
            linkedin_id_token = token_data.get("id_token")
            if not linkedin_access_token:
                raise LinkedInOAuthError("LinkedIn did not return an access token.")
            if not linkedin_id_token:
                raise LinkedInOAuthError("LinkedIn did not return an ID token.")

            userinfo_response = await client.get(
                LINKEDIN_USERINFO_URL,
                headers={"Authorization": f"Bearer {linkedin_access_token}"},
            )
            if userinfo_response.status_code != 200:
                logger.warning(
                    "LinkedIn userinfo request failed with status %s",
                    userinfo_response.status_code,
                )
                raise LinkedInOAuthError(
                    "LinkedIn profile information could not be loaded."
                )

            userinfo = userinfo_response.json()
            email = self._verified_email(userinfo)
            if not email:
                raise LinkedInOAuthError(
                    "LinkedIn must provide a verified email address."
                )

            first_name, last_name = self._profile_names(userinfo)
            linkedin_sub = str(userinfo.get("sub") or "").strip()
            if not linkedin_sub:
                raise LinkedInOAuthError("LinkedIn did not return a subject claim.")

            picture = userinfo.get("picture")
            normalized_picture = (
                picture.strip()
                if isinstance(picture, str) and picture.strip()
                else None
            )
            invitation_token = state_payload.get("invitation_token")
            normalized_invitation = (
                invitation_token.strip()
                if isinstance(invitation_token, str) and invitation_token.strip()
                else None
            )
            return OAuthVerifiedIdentity(
                provider="linkedin",
                email=email,
                first_name=first_name,
                last_name=last_name,
                provider_sub=linkedin_sub,
                picture=normalized_picture,
                invitation_token=normalized_invitation,
                terms_accepted=bool(state_payload.get("terms_accepted", False)),
            )

    def _ensure_configuration(self) -> None:
        """Validate the credentials required by the complete OAuth flow."""
        required_values = {
            "linkedin_client_id": getattr(self.settings, "linkedin_client_id", None),
            "linkedin_client_secret": getattr(
                self.settings, "linkedin_client_secret", None
            ),
            "jwt_secret_key": getattr(self.settings, "jwt_secret_key", None),
        }
        if any(not value for value in required_values.values()):
            missing = [name for name, value in required_values.items() if not value]
            env_hint = (
                "Set LINKEDIN_CLIENT_ID and LINKEDIN_CLIENT_SECRET in the root "
                ".env file, or use SUPABASE_AUTH_EXTERNAL_LINKEDIN_OIDC_CLIENT_ID "
                "and SUPABASE_AUTH_EXTERNAL_LINKEDIN_OIDC_CLIENT_SECRET in the root "
                ".env file."
            )
            raise LinkedInOAuthConfigurationError(
                f"LinkedIn OAuth is not configured. Missing: {', '.join(missing)}. "
                f"{env_hint}"
            )
        scopes = str(getattr(self.settings, "linkedin_oauth_scopes", "")).split()
        if "openid" not in scopes:
            raise LinkedInOAuthConfigurationError(
                "LINKEDIN_OAUTH_SCOPES must include openid."
            )

    @staticmethod
    def _profile_names(userinfo: Mapping[str, Any]) -> tuple[str, str]:
        """Extract display names from LinkedIn OIDC userinfo claims."""
        given_name = userinfo.get("given_name")
        family_name = userinfo.get("family_name")
        if isinstance(given_name, str) and given_name.strip():
            first_name = given_name.strip()
            last_name = (
                family_name.strip()
                if isinstance(family_name, str) and family_name.strip()
                else ""
            )
            return first_name, last_name

        full_name = userinfo.get("name")
        if isinstance(full_name, str) and full_name.strip():
            parts = full_name.strip().split(" ", 1)
            return parts[0], parts[1] if len(parts) > 1 else ""

        return "", ""

    @staticmethod
    def _verified_email(userinfo: Mapping[str, Any]) -> str | None:
        """Return a normalized email only when LinkedIn marks it verified."""
        email = userinfo.get("email")
        verified = userinfo.get("email_verified")
        if (
            not isinstance(email, str)
            or not email.strip()
            or verified is not True
            and str(verified).lower() != "true"
        ):
            return None
        return email.strip().lower()


linkedin_oauth_service = LinkedInOAuthService()
