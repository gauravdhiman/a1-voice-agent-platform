#!/usr/bin/env python3
"""Create .env.staging from an existing production/cloud env file.

Copies Stripe, OAuth, and other shared keys from the source file and swaps
Supabase URLs/keys to the staging project (gdzwiwukcwbqohfwxxrx).

You must still set staging-only secrets from Supabase dashboard:
  - SUPABASE_SERVICE_KEY
  - DATABASE_URL (database password)

Usage:
  python3 scripts/create-env-staging.py
  python3 scripts/create-env-staging.py --from .env.cloud
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

STAGING_REF = "gdzwiwukcwbqohfwxxrx"
PROD_REF = "zymiyfilulmtrmyyhvzw"
STAGING_ANON = (
    "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9."
    "eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6Imdkendpd3VrY3dicW9oZnd4eHJ4Iiwicm9sZSI6ImFub24iLCJpYXQiOjE3NzI0MDAwNzYsImV4cCI6MjA4Nzk3NjA3Nn0."
    "_1yrdH7cDRwarfaC7kcnyAP17BsMbFIJ9mJ2TaZaUrg"
)
HEADER = """# Cloud STAGING — oc-dev-ai-voice-agent-platform (gdzwiwukcwbqohfwxxrx)
# Generated by scripts/create-env-staging.py
#
# REQUIRED: set SUPABASE_SERVICE_KEY (Secret key) and DATABASE_URL from:
#   https://supabase.com/dashboard/project/gdzwiwukcwbqohfwxxrx/settings/api-keys
#   https://supabase.com/dashboard/project/gdzwiwukcwbqohfwxxrx?showConnect=true
#
# Then: ./scripts/bootstrap-staging-db.sh && cp .env.staging .env

"""


def _replace_line(key: str, value: str, staging_ref: str) -> str:
    """Apply staging-specific overrides for known keys."""
    if key in {
        "SUPABASE_URL",
        "NEXT_PUBLIC_SUPABASE_URL",
    }:
        return f"https://{staging_ref}.supabase.co"
    if key in {"SUPABASE_ANON_KEY", "NEXT_PUBLIC_SUPABASE_ANON_KEY"}:
        return STAGING_ANON
    if key == "SUPABASE_SERVICE_KEY":
        return "REPLACE_WITH_STAGING_SECRET_KEY"
    if key == "ENVIRONMENT":
        return "staging"
    if key == "DATABASE_URL":
        return (
            f"postgresql://postgres.{staging_ref}:"
            "REPLACE_WITH_URL_ENCODED_DB_PASSWORD"
            "@aws-0-us-west-2.pooler.supabase.com:5432/postgres"
        )
    if key == "APP_NAME":
        return "24x7 AI"
    if key == "NEXT_PUBLIC_APP_NAME":
        return "24x7 AI"
    if key == "RESEND_FROM_NAME":
        return "24x7 AI"
    if key == "APP_BASE_URL":
        return "http://localhost:3000"
    if key == "CORS_ORIGINS":
        return (
            '["http://localhost:3000", "http://127.0.0.1:3000", '
            '"http://frontend:3000", "http://frontend-dev:3000"]'
        )
    return value


def main() -> int:
    parser = argparse.ArgumentParser(description="Create .env.staging from prod env")
    parser.add_argument(
        "--from",
        dest="source",
        default=None,
        help="Source env file (default: .env.cloud, else .env.dev)",
    )
    parser.add_argument(
        "--out",
        default=".env.staging",
        help="Output path (default: .env.staging)",
    )
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[1]
    source = Path(args.source) if args.source else None
    if source is None:
        for candidate in (root / ".env.cloud", root / ".env.dev"):
            if candidate.is_file():
                source = candidate
                break
    if source is None or not source.is_file():
        print("No source env file found (.env.cloud or .env.dev)", flush=True)
        return 1

    out_lines = [HEADER]
    prod_anon_pattern = re.compile(rf"ref={PROD_REF}.*role.*anon")

    for raw in source.read_text().splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            out_lines.append(raw)
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip()

        if prod_anon_pattern.search(value.replace(" ", "")):
            value = STAGING_ANON
        if PROD_REF in value:
            value = value.replace(PROD_REF, STAGING_REF)
        if "aws-1-us-east-2" in value:
            value = value.replace("aws-1-us-east-2", "aws-0-us-west-2")

        value = _replace_line(key, value, STAGING_REF)
        out_lines.append(f"{key}={value}")

    out_path = root / args.out
    out_path.write_text("\n".join(out_lines) + "\n")
    print(f"Wrote {out_path} from {source.name}")
    print("Next: set SUPABASE_SERVICE_KEY and DATABASE_URL, then ./scripts/bootstrap-staging-db.sh")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
