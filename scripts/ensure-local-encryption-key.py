#!/usr/bin/env python3
"""Ensure a local environment file has a valid Fernet keyring configuration.

This helper only handles local, ignored environment files. Staging and
production keys remain deployment-managed secrets and are never generated by
the application launchers.
"""

from __future__ import annotations

import argparse
import base64
import binascii
import secrets
from pathlib import Path


def _is_fernet_key(value: str) -> bool:
    """Return whether ``value`` is canonical base64 for 32 raw key bytes."""
    try:
        decoded = base64.urlsafe_b64decode(value.encode("ascii"))
    except (ValueError, UnicodeError, binascii.Error):
        return False
    return (
        len(value) == 44
        and len(decoded) == 32
        and base64.urlsafe_b64encode(decoded).decode("ascii") == value
    )


def _read_value(lines: list[str], name: str) -> str:
    """Read one simple ``NAME=value`` entry without sourcing the file."""
    for line in lines:
        if line.startswith(f"{name}="):
            return line.split("=", 1)[1].strip().strip("\"'")
    return ""


def _replace_value(lines: list[str], name: str, value: str) -> None:
    """Replace or append one simple ``NAME=value`` entry."""
    replacement = f"{name}={value}"
    for index, line in enumerate(lines):
        if line.startswith(f"{name}="):
            lines[index] = replacement
            return
    if lines and lines[-1] != "":
        lines.append("")
    lines.append(replacement)


def ensure_key(path: Path, *, force_generate: bool = False) -> None:
    """Generate a local key when needed and remove malformed fallbacks."""
    lines = path.read_text(encoding="utf-8").splitlines()
    current_key = _read_value(lines, "ENCRYPTION_KEY")
    if force_generate or not _is_fernet_key(current_key):
        current_key = base64.urlsafe_b64encode(secrets.token_bytes(32)).decode("ascii")
        _replace_value(lines, "ENCRYPTION_KEY", current_key)

    # A malformed fallback makes the backend reject the entire keyring. Keep
    # valid rotation keys and remove only placeholders or malformed entries.
    fallback_values = [
        value.strip()
        for value in _read_value(lines, "ENCRYPTION_KEY_FALLBACKS").split(",")
        if value.strip() and _is_fernet_key(value.strip())
    ]
    _replace_value(lines, "ENCRYPTION_KEY_FALLBACKS", ",".join(fallback_values))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("env_file", type=Path)
    parser.add_argument(
        "--force",
        action="store_true",
        help="generate a new key even when the current key is valid",
    )
    args = parser.parse_args()
    ensure_key(args.env_file, force_generate=args.force)


if __name__ == "__main__":
    main()
